// Package scaffold materialises the embedded project starter and keeps the
// generated plugin registration file in sync with mre.toml.
package scaffold

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Shrawan-13/mre/cli/internal/project"
	tmpl "github.com/Shrawan-13/mre/cli/internal/templates"
	"github.com/Shrawan-13/mre/cli/internal/version"
)

// Create writes a new project at root. It refuses to overwrite a non-empty
// directory so an accidental `mre new .` cannot destroy work.
func Create(root string, cfg project.Config) error {
	if entries, err := os.ReadDir(root); err == nil && len(entries) > 0 {
		return fmt.Errorf("directory %s is not empty", root)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(root, 0o755); err != nil {
		return err
	}
	err := fs.WalkDir(tmpl.FS, tmpl.Prefix, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(tmpl.Prefix, path)
		if err != nil {
			return err
		}
		target := filepath.Join(root, filepath.FromSlash(relative))
		if entry.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		data, err := tmpl.FS.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, []byte(render(string(data), cfg)), 0o644)
	})
	if err != nil {
		return err
	}
	return WritePlugins(root, cfg)
}

func render(source string, cfg project.Config) string {
	for key, value := range map[string]string{
		"{{APP_NAME}}":       cfg.Name,
		"{{APP_ID}}":         cfg.AndroidAppID,
		"{{APP_LABEL}}":      cfg.AndroidLabel,
		"{{ENGINE_VERSION}}": cfg.Engine,
	} {
		source = strings.ReplaceAll(source, key, value)
	}
	return source
}

// WritePlugins regenerates Plugins.java from the manifest. The file is marked
// generated so editing it by hand is never the right fix.
func WritePlugins(root string, cfg project.Config) error {
	names := append([]string(nil), cfg.Plugins...)
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("package dev.mre;\n\n")
	b.WriteString("import android.content.Context;\n")
	b.WriteString("import java.util.ArrayList;\nimport java.util.List;\n")
	for _, name := range names {
		fmt.Fprintf(&b, "import dev.mre.plugin.%sPlugin;\n", Export(name))
	}
	b.WriteString(`
/**
 * Generated by ` + "`mre plugin new`" + `. Do not edit by hand.
 */
public final class Plugins {
    private Plugins() { }

    public static List<MrePlugin> create(Context context) {
        List<MrePlugin> plugins = new ArrayList<>();
`)
	for _, name := range names {
		fmt.Fprintf(&b, "        plugins.add(new %sPlugin());\n", Export(name))
	}
	b.WriteString("        return plugins;\n    }\n}\n")
	path := filepath.Join(root, "android", "app", "src", "main", "java", "dev", "mre", "Plugins.java")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// AddPlugin scaffolds one native plugin: the Lua wrapper, the Java
// implementation, and the generated registration file.
func AddPlugin(root string, cfg project.Config, name string) error {
	if name == "" || strings.ContainsAny(name, "/\\ .") {
		return fmt.Errorf("invalid plugin name %q", name)
	}
	for _, existing := range cfg.Plugins {
		if existing == name {
			return fmt.Errorf("plugin %q already exists", name)
		}
	}
	export := Export(name)

	luaDir := filepath.Join(root, "plugins", name)
	if err := os.MkdirAll(luaDir, 0o755); err != nil {
		return err
	}
	lua := fmt.Sprintf(`-- Native plugin %q, generated by `+"`mre plugin new`"+`.
--
-- Add methods to the Java implementation, then call them from Lua with
-- mre.platform_call(%q, method, args).
mre.plugins.%s = {}
`, name, name, name)
	if err := os.WriteFile(filepath.Join(luaDir, "init.lua"), []byte(lua), 0o644); err != nil {
		return err
	}

	javaDir := filepath.Join(root, "plugins", name, "android", "dev", "mre", "plugin")
	if err := os.MkdirAll(javaDir, 0o755); err != nil {
		return err
	}
	java := fmt.Sprintf(`package dev.mre.plugin;

import dev.mre.MrePlugin;

/** Native extension %q. Generated by `+"`mre plugin new`"+`. */
public final class %sPlugin implements MrePlugin {
    @Override public String name() { return %q; }

    @Override
    public String call(String method, String args) {
        switch (method) {
            // Add your native methods here. Always return a string.
            default:
                return "";
        }
    }
}
`, name, export, name)
	source := filepath.Join(javaDir, export+"Plugin.java")
	if err := os.WriteFile(source, []byte(java), 0o644); err != nil {
		return err
	}

	// Gradle only compiles app/src/main/java, so copy the implementation there.
	appDir := filepath.Join(root, "android", "app", "src", "main", "java", "dev", "mre", "plugin")
	if err := os.MkdirAll(appDir, 0o755); err != nil {
		return err
	}
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(appDir, export+"Plugin.java"), data, 0o644); err != nil {
		return err
	}

	cfg.Plugins = append(cfg.Plugins, name)
	manifest := filepath.Join(root, "mre.toml")
	if err := os.WriteFile(manifest, []byte(cfg.String()), 0o644); err != nil {
		return err
	}
	return WritePlugins(root, cfg)
}

// Export turns a plugin name into a Java class prefix.
func Export(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' })
	var b strings.Builder
	for _, part := range parts {
		runes := []rune(part)
		if len(runes) == 0 {
			continue
		}
		b.WriteString(strings.ToUpper(string(runes[0])))
		b.WriteString(string(runes[1:]))
	}
	return b.String()
}

