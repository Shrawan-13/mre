//! Compiles `perf/budget.toml` into typed constants.
//!
//! The point of doing this at build time rather than at runtime is that the
//! budget becomes part of the program: gates are `const` comparisons, the file
//! is the single source of truth, and there is no TOML parser in the shipped
//! binary.

use std::{env, fs, path::PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let budget_path = manifest_dir.join("../../perf/budget.toml");

    println!("cargo:rerun-if-changed={}", budget_path.display());
    println!("cargo:rerun-if-changed=build.rs");

    let text = fs::read_to_string(&budget_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", budget_path.display()));
    let parsed: toml::Value = text
        .parse()
        .unwrap_or_else(|e| panic!("cannot parse {}: {e}", budget_path.display()));

    let sections = parsed
        .as_table()
        .expect("perf/budget.toml must contain tables");

    let mut modules = String::new();
    let mut flat: Vec<(String, String, String)> = Vec::new();

    for (section, section_value) in sections {
        let table: &toml::map::Map<String, toml::Value> = section_value
            .as_table()
            .unwrap_or_else(|| panic!("[{section}] in budget.toml must be a table"));

        let module = ident(section);
        modules.push_str(&format!(
            "/// Values from `[{section}]` in `perf/budget.toml`.\n\
             #[allow(missing_docs)]\n\
             pub mod {module} {{\n"
        ));
        for (key, value) in table {
            let name = ident(key).to_uppercase();
            let (ty, literal) = match value {
                toml::Value::Integer(i) => ("i64", i.to_string()),
                toml::Value::Float(f) => ("f64", format!("{f:?}")),
                toml::Value::Boolean(b) => ("bool", b.to_string()),
                toml::Value::String(s) => ("&'static str", format!("{s:?}")),
                other => panic!("unsupported value type in {section}.{key}: {other:?}"),
            };
            modules.push_str(&format!("    pub const {name}: {ty} = {literal};\n"));
            flat.push((
                section.clone(),
                key.clone(),
                flat_value(value, section, key),
            ));
        }
        modules.push_str("}\n\n");
    }

    let mut table = String::from(
        "/// Every value in `perf/budget.toml`, for tooling that needs to look\n\
         /// budgets up by name rather than through the typed constants.\n\
         pub static TABLE: &[(&str, &str, Value)] = &[\n",
    );
    for (section, key, value) in &flat {
        table.push_str(&format!("    ({section:?}, {key:?}, {value}),\n"));
    }
    table.push_str("];\n");

    let generated = format!(
        "// @generated by mre-perf/build.rs from perf/budget.toml -- do not edit.\n\
         \n\
         /// One budget value of any supported type.\n\
         #[derive(Debug, Clone, Copy, PartialEq)]\n\
         pub enum Value {{\n\
         \x20   /// Integer budget (durations in ns, sizes in bytes, counts).\n\
         \x20   Int(i64),\n\
         \x20   /// Floating-point budget (ratios).\n\
         \x20   Float(f64),\n\
         \x20   /// Boolean budget.\n\
         \x20   Bool(bool),\n\
         \x20   /// String budget.\n\
         \x20   Str(&'static str),\n\
         }}\n\
         \n\
         {modules}\
         {table}\
         \n\
         /// Looks a budget value up by section and key.\n\
         #[must_use]\n\
         pub fn get(section: &str, key: &str) -> Option<Value> {{\n\
         \x20   TABLE.iter().find(|(s, k, _)| *s == section && *k == key).map(|(_, _, v)| *v)\n\
         }}\n"
    );

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("budget_gen.rs");
    fs::write(&out, generated).unwrap_or_else(|e| panic!("cannot write {}: {e}", out.display()));
}

fn flat_value(value: &toml::Value, section: &str, key: &str) -> String {
    match value {
        toml::Value::Integer(i) => format!("Value::Int({i})"),
        toml::Value::Float(f) => format!("Value::Float({f:?})"),
        toml::Value::Boolean(b) => format!("Value::Bool({b})"),
        toml::Value::String(s) => format!("Value::Str({s:?})"),
        other => panic!("unsupported value type in {section}.{key}: {other:?}"),
    }
}

/// Turns a TOML key into a valid Rust identifier.
fn ident(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for (i, ch) in raw.chars().enumerate() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            if i == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}
